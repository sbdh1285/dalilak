def art_body_bounds(text: str) -> tuple[int, int]:
    """حدود جسم المقال: من فتح art-body إلى أول قسم لاحق (مصادر/عناقيد/مشاركة)."""
    start = text.index('<div class="art-body">')
    candidates = [
        text.find("<!-- CLUSTER-LINKS-START -->", start),
        text.find('<section class="cluster-links"', start),
        text.find('<section class="sources"', start),
        text.find('<div class="share">', start),
    ]
    ends = [c for c in candidates if c > start]
    return start, (min(ends) if ends else len(text))


def section_end(body: str, h2_open: str) -> int:
    """نهاية القسم الذي يبدأ بـ h2_open داخل body: بداية أول h2 تالٍ."""
    i = body.find(h2_open)
    if i < 0:
        return -1
    nxt = re.search(r"<h2\b", body[i + len(h2_open):])
    return (i + len(h2_open) + nxt.start()) if nxt else len(body)


def apply(slug: str, ops: list[tuple[str, str, str]]) -> str:
    path = POSTS / f"{slug}.html"
    if not path.exists():
        return f"✗ {slug}: الملف غير موجود"
    text = path.read_text(encoding="utf-8")
    start, end = art_body_bounds(text)
    body = text[start:end]

    # idempotency: أزل أي إدراج سابق من هذا السكربت قبل إعادة التطبيق،
    # مع ابتلاع المسافات المحيطة حتى لا تتراكم أسطر فارغة عند كل تشغيل.
    body = re.sub(
        r"\s*" + re.escape(MARK_START) + r".*?" + re.escape(MARK_END) + r"\s*",
        "\n",
        body,
        flags=re.S,
    )

    for mode, anchor, html_block in ops:
        chunk = MARK_START + html_block.strip() + MARK_END
        if mode == "after":
            pos = section_end(body, anchor)
            if pos < 0:
                return f"✗ {slug}: لم يُعثر على المرساة {anchor}"
            body = body[:pos] + "\n" + chunk + "\n" + body[pos:]
        else:  # before
            pos = body.find(anchor)
            if pos < 0:
                return f"✗ {slug}: لم يُعثر على المرساة {anchor}"
            body = body[:pos] + chunk + "\n" + body[pos:]

    # حارس: كل h2 لا بد أن يحمل id وإلا حذفه remove_post_conclusion_extras.
    bad = re.findall(r"<h2(?! id=)[^>]*>", body)
    if bad:
        return f"✗ {slug}: عناوين h2 بلا id ستُحذف: {bad}"

    # حارس: ضع علامة PROF-2026 لتفادي إعادة كتابة الجسم من السكربتات الأخرى.
    if "<!-- PROF-2026 -->" not in body:
        body = body.replace(
            '<div class="art-body">', '<div class="art-body"><!-- PROF-2026 -->', 1
        )

    path.write_text(text[:start] + body + text[end:], encoding="utf-8")

    # زامن جدول المحتويات ومدة القراءة مع العناوين الجديدة.
    sync_toc(slug)
    set_art_meta_minutes(slug)
    return f"✓ {slug}"


def dedupe_accuracy_notes() -> list[str]:
    """أزل تكرار كتلة accuracy-note داخل المقال الواحد.

    سببه أن ``enhance_supporting`` يحقن نسخة محدّثة داخل SUPPORT-REVIEW بينما
    نسخة أقدم من الكتلة نفسها ما زالت موجودة في الملف. نُبقي النسخة الواردة
    داخل SUPPORT-REVIEW (الأحدث والأكمل) ونحذف ما عداها.
    """
    fixed = []
    for path in sorted(POSTS.glob("*.html")):
        text = path.read_text(encoding="utf-8")
        notes = list(re.finditer(r'<div class="accuracy-note">.*?</p></div>', text, re.S))
        if len(notes) < 2:
            continue
        sup = re.search(
            r"<!-- SUPPORT-REVIEW-START -->.*?<!-- SUPPORT-REVIEW-END -->", text, re.S
        )
        # احذف من الآخر إلى الأول حتى لا تتغير المواضع، مع إبقاء ما داخل SUPPORT.
        removed = 0
        for m in reversed(notes):
            inside = bool(sup and sup.start() <= m.start() < sup.end())
            if inside or removed >= len(notes) - 1:
                continue
            text = text[: m.start()] + text[m.end():]
            removed += 1
        if removed:
            path.write_text(text, encoding="utf-8")
            fixed.append(f"{path.stem} (-{removed})")
    return fixed


def main() -> None:
    results = [apply(slug, ops) for slug, ops in BLOCKS.items()]
    dd = dedupe_accuracy_notes()
    if dd:
        print('إزالة تكرار ملاحظات الدقة:', ', '.join(dd))
    for r in results:
        print(r)
    failures = [r for r in results if r.startswith("✗")]
    if failures:
        sys.exit(1)
    print(f"\nتم تعميق {len(BLOCKS)} مقالًا.")


if __name__ == "__main__":
    main()
